// Embeds deploy/cloudflare-worker/worker.js in the CLI so `waypost setup cloudflare` uploads the same front door
// that wrangler users deploy. Runs before every build; the test suite fails if the two copies differ.
import { readFile, writeFile } from 'node:fs/promises';

const source = await readFile(new URL('../deploy/cloudflare-worker/worker.js', import.meta.url), 'utf8');
await writeFile(new URL('../src/worker-source.ts', import.meta.url), `// Generated by scripts/embed-worker.mjs from deploy/cloudflare-worker/worker.js. Do not edit.\nexport const WORKER_SOURCE:string=${JSON.stringify(source)};\n`);
